"""Ghep cac loi giai hien co thanh ban LaTeX co muc luc va tieu de."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = (
    "loi_giai_1.tex", "loi_giai_soc.tex", "loi_giai_2.tex",
    "loi_giai_3a.tex", "loi_giai_3_graph.tex", "loi_giai_3b.tex",
)
inventory = {item["id"]: item for item in json.loads(
    (ROOT / "inventory.json").read_text(encoding="utf-8"))}
blocks = []
seen = set()
for source in SOURCES:
    content = (ROOT / source).read_text(encoding="utf-8-sig")
    matches = list(re.finditer(r"^%ID\s+(\S+)\s*$", content, re.MULTILINE))
    for index, match in enumerate(matches):
        identity = match.group(1)
        if identity in seen:
            raise ValueError(f"Duplicate solution: {identity}")
        seen.add(identity)
        end = matches[index + 1].start() if index + 1 < len(matches) else len(content)
        body = content[match.end():end].strip()
        item = inventory[identity]
        blocks.append((item, source, body))

preamble = r"""% Generated by _xu_ly/tao_ban_de_doc.py. Edit the source solution files.
\documentclass[11pt,a4paper]{article}
\usepackage{fontspec}
\usepackage{amsmath,amssymb}
\usepackage[margin=18mm]{geometry}
\usepackage{graphicx}
\usepackage[unicode,colorlinks=true,linkcolor=blue]{hyperref}
\setmainfont{Times New Roman}
\renewcommand{\contentsname}{Mục lục}
\setcounter{secnumdepth}{0}
\setcounter{tocdepth}{2}
\setlength{\parindent}{0pt}
\setlength{\parskip}{5pt}
\emergencystretch=3em
\newsavebox{\mathbox}
\newcommand{\fitmath}[1]{%
  \sbox{\mathbox}{$\displaystyle\begin{gathered}#1\end{gathered}$}%
  \ifdim\wd\mathbox>\linewidth
    \resizebox{\linewidth}{!}{\usebox{\mathbox}}%
  \else\usebox{\mathbox}\fi}
\hypersetup{pdftitle={Lời giải PDE — tổng hợp các phần hiện có}}
\begin{document}
\begin{center}
{\LARGE\bfseries LỜI GIẢI BÀI TẬP PDE}\\[8pt]
{\large Tổng hợp các phần hiện có}
\end{center}

Bản này tập hợp lời giải hiện có của Chương 1, Chương 2 và một phần
Chương 3. Đây chưa phải lời giải đầy đủ của toàn bộ tài liệu.
Nội dung được giữ từ các file lời giải; bản này chỉ bổ sung mục lục,
tiêu đề bài và định dạng để đọc thuận tiện.

Ký hiệu: BT là bài tập, VD là ví dụ, NC là bài nâng cao.
Số trang đối chiếu là số trang trong file PDF đề gốc.

\tableofcontents
\clearpage
"""
parts = [preamble]
chapter = None
group = None
labels = {"BT": "Bài tập", "VD": "Ví dụ", "NC": "Bài nâng cao"}
for item, source, body in blocks:
    current_chapter = item["section"].split(".")[0]
    if current_chapter != chapter:
        if chapter is not None:
            parts.append(r"\clearpage")
        parts.append(r"\section{Chương " + current_chapter + "}")
        chapter = current_chapter
        group = None
    current_group = (item["kind"], item["section"])
    if current_group != group:
        parts.append(r"\subsection{" + labels[item["kind"]] + " — Mục " + item["section"] + "}")
        group = current_group
    parts.append(r"\subsubsection{" + labels[item["kind"]] + " " + str(item["number"]) + "}")
    parts.append(r"{\small\itshape Đối chiếu đề gốc: trang " + str(item["start"][0]) + ".}")
    parts.append("% Source: " + source + "; ID: " + item["id"])
    body = re.sub(r"\\\[(.*?)\\\]", lambda m: r"\[\fitmath{" + m.group(1) + r"}\]", body, flags=re.DOTALL)
    parts.append(body)
parts.append(r"\end{document}")
target = ROOT.parent / "loi_giai_tong_hop.tex"
target.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
print(f"Created {target.name}: {len(blocks)} solutions from {len(SOURCES)} sources.")
